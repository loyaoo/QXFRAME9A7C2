// Generate src/styles/main/theme.css — qxframe.css's default theme block — from the
// createApp compiler: one closed :root Token block; color tokens use light-dark(),
// .dark and CSS-only inverse Menu roots change only color-scheme.
// `--check` fails when the committed file differs from the compiler output.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'src/styles/main/theme.css');
const model = await import(pathToFileURL(path.join(root, 'docs/create/model.js')).href);

const embeddedTheme = model.normalizeConfig({
  // The default baked into qxframe9a7c2.css, independent of Create's reset.
  style: 'vega', baseColor: 'mist', theme: 'blue', chartColor: 'blue',
  font: 'sans', fontHeading: 'inherit', radius: 'default',
  menuColor: 'default', menuAccent: 'subtle',
  ext: { menuInset: 'block', switchLook: 'wide', shadow: 'medium',
    pointerFocus: 'outline', pointerFocusColor: 'theme', shapeThumb: 'pill' }
});
const { body } = model.compileTheme(embeddedTheme);
const text = '/* Default theme (generated by tools/build-theme.mjs from docs/create/compiler.js; do not edit).\n'
  + ' * Vega + Mist base + Blue accent (owner-provided 2026-10-16). Single Token owner; .dark selects the scheme without repeating colors. */\n' + body;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== text) {
    console.error('theme.css is stale: run `node tools/build-theme.mjs`.');
    process.exit(1);
  }
  console.log(JSON.stringify({ ok: true, bytes: Buffer.byteLength(text) }));
} else {
  fs.writeFileSync(target, text);
  console.log(JSON.stringify({ ok: true, wrote: path.relative(root, target), bytes: Buffer.byteLength(text) }));
}
