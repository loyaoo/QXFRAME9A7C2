// Generate src/styles/main/theme-default.css — qxframe.css's default theme block — from the
// createApp compiler (v3 §5.2, §5.10: Nova + neutral, full closed list, :root + .dark).
// `--check` fails when the committed file differs from the compiler output.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'src/styles/main/theme-default.css');
const model = await import(pathToFileURL(path.join(root, 'docs/create/model.js')).href);

const { body } = model.compileTheme(model.defaultConfig());
const text = '/* Default theme (generated by tools/build-theme-default.mjs from docs/create/compiler.js; do not edit).\n'
  + ' * Nova + neutral. Only --qxframe9a7c2-theme-* tokens under :root and .dark (v3 §5). */\n' + body;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== text) {
    console.error('theme-default.css is stale: run `node tools/build-theme-default.mjs`.');
    process.exit(1);
  }
  console.log(JSON.stringify({ ok: true, bytes: Buffer.byteLength(text) }));
} else {
  fs.writeFileSync(target, text);
  console.log(JSON.stringify({ ok: true, wrote: path.relative(root, target), bytes: Buffer.byteLength(text) }));
}
