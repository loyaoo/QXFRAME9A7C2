const createInitializer = Object.freeze({ initializer:Object.freeze({ mode:'create', bind:'container' }) });
const enhanceInitializer = Object.freeze({ initializer:Object.freeze({ mode:'enhance' }) });
const sourceInitializer = Object.freeze({ initializer:Object.freeze({ mode:'create', bind:'source' }) });
const referenceInitializer = Object.freeze({ initializer:Object.freeze({ mode:'create', bind:'reference' }) });
const noInitializer = Object.freeze({ initializer:false });

function classApi(Type, extras = {}) {
    const base = { definition:createInitializer, create:function(){ return Type.create.apply(Type, arguments); } };
    if (Type.profile) base.profile = Type.profile;
    return Object.freeze(Utils.assignOwn(base, extras));
}
const raw = Object.create(null);
raw.Cascader = classApi(Cascader, { definition:enhanceInitializer, enhance:function(){return Cascader.enhance.apply(Cascader,arguments);}, createDefaultDOM:Cascader.createDefaultDOM });
raw.TreeSelect = classApi(TreeSelect, { definition:enhanceInitializer, enhance:function(){return TreeSelect.enhance.apply(TreeSelect,arguments);}, createDefaultDOM:TreeSelect.createDefaultDOM });
raw.Select = classApi(Select, { definition:enhanceInitializer, enhance:function(){return Select.enhance.apply(Select,arguments);}, createDefaultDOM:Select.createDefaultDOM });
