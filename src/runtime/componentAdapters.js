raw.Dropdown = classApi(Dropdown, { definition:referenceInitializer });
raw.Modal = classApi(Modal, { definition:noInitializer, placements:MODAL_PLACEMENTS.slice() });
raw.Drawer = classApi(Drawer, { definition:noInitializer, placements:DRAWER_PLACEMENTS.slice(), animations:DRAWER_ANIMATIONS.slice() });
raw.Result = classApi(Result, { names:Result.names });
raw.WheelPicker = classApi(WheelPicker, { definition:enhanceInitializer, enhance:function(){return WheelPicker.enhance.apply(WheelPicker,arguments);} });
raw.TimePicker = classApi(TimePicker, { definition:enhanceInitializer, enhance:function(){return TimePicker.enhance.apply(TimePicker,arguments);}, formatTime:TimePicker.formatTime, parseTime:TimePicker.parseTime });
