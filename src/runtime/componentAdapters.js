raw.Tooltip = classApi(Tooltip, { definition:referenceInitializer });
raw.TagInput = classApi(TagInput, { definition:enhanceInitializer, enhance:function(){return TagInput.enhance.apply(TagInput,arguments);} });
raw.Popconfirm = classApi(Popconfirm, { definition:referenceInitializer });
